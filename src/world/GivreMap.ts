/**
 * "GIVRE 01 — Station alpine" (8 players, 280 × 220 m) — v3 content.
 *
 * Visuals: givre_01.glb (292 nodes / ~175k tris / 25 PBR materials,
 * metres, already Y-up — NO extra rotation or scale). v3 materials carry
 * BAKED LIGHT on the `uv` attribute: `emissiveMap` (image givre_lumiere —
 * ceiling lamps, garlands, lanterns, boiler fire) and `aoMap` (image
 * givre_ao — sky visibility, switches the hemisphere ambient off inside
 * rooms). The glb materials are KEPT as-is (never replaced).
 *  - STATIC meshes are merged by material (position + normal + uv kept),
 *    then split on a coarse XZ grid (frustum culling + front-to-back draw)
 *    and thin closed solids drawn single-sided — ~70 batches, each with a
 *    BVH for the shot raycasts (see GivreRenderOptim / GivreConfig).
 *  - ANIMATED nodes (targets of the single 8 s glTF clip + their children:
 *    steam, smoke, garlands, banners, boiler, gauges, fans, beacon) stay
 *    separate and are driven by GivreEffects' AnimationMixer. The 95
 *    smoke / steam puffs (6 shared geometries) are drawn by 6 InstancedMesh
 *    whose matrices are copied from the (hidden) animated nodes.
 * The out-of-bounds plain + mountains (givre_01_fond.glb, no shadow, no
 * collision) live in a separate `backdrop` group.
 *
 * Shot raycasts: only `hittables` (merged static meshes + the animated
 * boiler, which has server colliders) — the purely decorative animated
 * décor (steam, smoke, banners, garlands, fans…) has NO collider on the
 * server, so it must never stop a shot client-side either.
 *
 * Collisions: the Yard-format physics JSON generated by
 * scripts/generate-givre-colliders.mjs — 307 fixed cuboids + 209 convex
 * hulls + 10 PLAYER CLIPS (9 boxes + 1 convex hull; CollisionGroups.
 * PLAYER_CLIP: they stop character controllers only — shots and lines of
 * sight pass through). Never a trimesh.
 *
 * Lighting: sun + hemisphere from GivreConfig, shadow camera FITTED to the
 * map seen from the low sun (rectangular shadow map); no live lamp — the
 * baked emissive lights the interiors. sRGB output without tone mapping is
 * applied by Game.
 */

// BVH-accelerated raycasting: see MapBvh (built after the loading screen).

/** v3: `uv` carries the baked light (emissiveMap + aoMap). */
const KEEP_ATTRIBUTES = new Set(["position", "normal", "uv"]);
/** Animated nodes sharing geometry + material at least this often → InstancedMesh. */
const INSTANCE_MIN = 4;
/** Material of the walkable snow (footprint surfaces). */
const SNOW_MATERIAL = "GIV_Neige";

/** Animated decoration of the glb (see GivreEffects). */
export interface GivreAnimatedDecor {
  /** GLB scene root holding the animated nodes — the mixer binds here. */
  readonly root: THREE.Object3D;
  /** The glTF clip(s) — v3: one 8 s loop. */
  readonly clips: THREE.AnimationClip[];
  /** Animated nodes by name (halos of the garlands attach to them). */
  readonly nodes: Map<string, THREE.Object3D>;
  /** Repeated puffs drawn by InstancedMesh (matrices copied every frame). */
  readonly instanced: { mesh: THREE.InstancedMesh; sources: THREE.Mesh[] }[];
}

export class GivreMap {
  /** Playable visual (merged + animated meshes) + lights. */
  readonly group = new THREE.Group();
  /**
   * Shot-raycast targets: the merged static meshes + the animated boiler
   * (it has server colliders). Every other animated node is visual only.
   */
  readonly hittables: THREE.Object3D[] = [];
  /** Out-of-bounds plain + mountains — added to the scene by Game, never hittable. */
  readonly backdrop: THREE.Group;
  /** Collider (magenta) / playerClip (cyan) wireframes — hidden by default. */
  private colliderDebugGroup: THREE.Group | null = null;
  /** Named zones (callouts). */
  readonly zones: GivreZone[];
  /** Merged snow meshes (material GIV_Neige) — footprint surfaces. */
  readonly snowSurfaces: THREE.Mesh[] = [];
  /** glb materials by name (e.g. GIV_Feu for the fire flicker). */
  readonly materials = new Map<string, THREE.Material>();
  /** Animated décor (mixer root, clip, nodes, instanced puffs). */
  readonly animated: GivreAnimatedDecor;
  /**
   * Options of the map's specialised shader this session (GivreMapMaterial):
   * the exact set by default, null with `?diag=nomapshader` (three's stock
   * shader), + the near-exact part with `?diag=mapshaderfast`.
   */
  readonly mapShader: Readonly<MapShaderOptions> | null;
  /** The meshes the specialised shader applies to, with their stock materials. */
  private readonly mapShaderTargets: MapShaderTarget[];
  /** Specialised clones by stock material + option set (one each, reused). */
  private readonly mapShaderMaterials = new Map<string, THREE.Material | null>();

  private constructor(
    physics: PhysicsWorld,
    gltf: { scene: THREE.Group; animations: THREE.AnimationClip[] },
    backdrop: THREE.Group,
  ) {
    const data = givreData;
    this.zones = data.zones;

    this.group.name = "givre_01";
    // Blender objects with colliders: an animated node among them (the
    // boiler) stays a shot target, consistent with the server's AABBs.
    const colliderSources = new Set<string>();
    for (const c of data.colliders) if (c.source) colliderSources.add(c.source);
    this.animated = this.buildVisual(gltf, colliderSources);
    this.buildLighting();

    backdrop.name = "givre_01_fond";
    backdrop.traverse((o) => {
      const mesh = o as THREE.Mesh;
      if (!mesh.isMesh) return;
      mesh.castShadow = false;
      mesh.receiveShadow = false;
      mesh.raycast = () => {}; // purely visual
    });
    this.backdrop = backdrop;

    // PERF: the map's shader specialised for what the map really uses
    // (GivreMapMaterial: no image-based light, metalness 0, one lightmap uv —
    // same pixels). Decided here, at load: the specialised materials are the
    // ones the GPU warm-up compiles. GIV_Feu keeps its shared instance (its
    // emissive flickers through it — GivreEffects).
    this.mapShaderTargets = collectMapShaderTargets([this.group, backdrop], DECOR_KEEP_MATERIALS);
    this.mapShader = mapShaderOptionsFor(perfExperiments());
    const specialised = applyMapShader(this.mapShaderTargets, this.mapShader, this.mapShaderMaterials);
    // One line on every build (the A/B on a real GPU reads which shader ran).
    console.info(
      this.mapShader
        ? `[CARTE] shader spécialisé (${mapShaderKey(this.mapShader)}) sur ${specialised} / ${this.mapShaderTargets.length} maillages`
        : "[CARTE] shader d'origine de three (?diag=nomapshader)",
    );
    if (import.meta.env.DEV) {
      // Bench / console A/B (DEV builds only — it compiles on first use):
      //   givreMapShader.set(null)              three's stock shader
      //   givreMapShader.set({ noIbl: true, … }) any option set (GivreMapMaterial)
      //   givreMapShader.list()                  mesh → option key
      (window as unknown as Record<string, unknown>).givreMapShader = {
        session: this.mapShader,
        set: (options: MapShaderOptions | null, extra?: { key: string; patch: ShaderPatch }) =>
          applyMapShader(this.mapShaderTargets, options, this.mapShaderMaterials, extra),
        list: () =>
          this.mapShaderTargets.map(
            (t) => `${t.mesh.name}: ${(t.mesh.material as THREE.Material).userData.mapShader ?? "stock"}`,
          ),
        key: mapShaderKey,
        chunks: THREE.ShaderChunk,
      };
    }

    // PERF: the map never moves — only the clip TARGETS animate (mixer).
    // Every other node (batches, holders, empties, the meshes riding an
    // animated node, halos, puff instances, lights, the backdrop) keeps a
    // constant LOCAL matrix: no recompose, and — with the scene root frozen
    // too (Game) — no forced world-matrix refresh of the whole map in the
    // two scene-graph updates of every frame. A node riding an animated
    // parent still follows it (the parent's update forces its subtree).
    const targets = new Set(this.animated.nodes.values());
    freezeStaticTransforms(this.group, targets);
    freezeStaticTransforms(backdrop);

    // ---- Fixed colliders (created ONCE; hull vertices already absolute) ----
    for (const c of data.colliders) {
      if (!addCollider(physics, c)) console.warn(`GivreMap: collider failed for "${c.id}"`);
    }
    // ---- Player clips: character controllers only (never shots / LOS) ----
    for (const c of data.playerClips) {
      if (!addCollider(physics, c, CollisionGroups.PLAYER_CLIP)) {
        console.warn(`GivreMap: player clip failed for "${c.id}"`);
      }
    }
  }

  /**
   * Collider wireframes (debug view), built on FIRST use: 527 meshes, one
   * convex hull each — tens of ms of loading for a view almost never shown.
   */
  get colliderDebug(): THREE.Group {
    this.colliderDebugGroup ??= createColliderDebug(givreData.colliders, givreData.playerClips);
    return this.colliderDebugGroup;
  }

  private static assets: Promise<[GLTF, GLTF]> | null = null;

  /**
   * Starts downloading + parsing both GLBs (idempotent): Game.create calls it
   * before the physics WASM starts, so both run side by side.
   */
  static preload(): void {
    if (GivreMap.assets) return;
    const loader = new GLTFLoader();
    GivreMap.assets = Promise.all([loader.loadAsync(mapModelUrl), loader.loadAsync(backdropModelUrl)]);
    GivreMap.assets.catch(() => {}); // reported by create()
  }

  /** Loads both GLBs (see preload) and builds every fixed collider. */
  static async create(physics: PhysicsWorld): Promise<GivreMap> {
    GivreMap.preload();
    const assets = GivreMap.assets!;
    GivreMap.assets = null; // the parsed files are not kept past the build
    let map;
    let backdrop;
    try {
      [map, backdrop] = await assets;
    } catch (err) {
      throw new Error(`GivreMap: failed to load givre_01.glb / givre_01_fond.glb — ${String(err)}`);
    }
    return new GivreMap(physics, map, backdrop.scene);
  }

  /** Zone name under a position (the gallery at Y = 6 wins over the ground). */
  zoneAt(x: number, y: number, z: number): string | null {
    let best: GivreZone | null = null;
    for (const zn of this.zones) {
      if (x < zn.min[0] || x > zn.max[0] || z < zn.min[1] || z > zn.max[1]) continue;
      if (!best || Math.abs(y - zn.floorY) < Math.abs(y - best.floorY)) best = zn;
    }
    return best ? best.name : null;
  }

  /**
   * Builds the v3 visual from the loaded glb (see the class header):
   *  1. finds the ANIMATED nodes (clip track targets + children);
   *  2. lightmaps (emissiveMap + aoMap) WITHOUT mipmaps — otherwise the UV
   *     islands of the baked atlas bleed into each other in the distance;
   *  3. merges every STATIC mesh by material (position + normal + uv);
   *  4. replaces the repeated animated puffs by InstancedMesh.
   * Returns the animated décor driven by GivreEffects (mixer root + clips).
   */
  private buildVisual(
    gltf: { scene: THREE.Group; animations: THREE.AnimationClip[] },
    colliderSources: ReadonlySet<string>,
  ): GivreAnimatedDecor {
    const scene = gltf.scene;
    scene.updateMatrixWorld(true);
    const { nodes, all: animated } = findAnimatedNodes(scene, gltf.animations);

    // Materials are KEPT from the glb (they carry the baked light) — only
    // their shader class may change (MeshPhysical → MeshStandard, see
    // GivreConfig.standardMaterials: same colours / textures / baked light).
    if (givre.standardMaterials) convertToStandardMaterials(scene);
    const lightmaps = new Set<THREE.Texture>();
    scene.traverse((o) => {
      const mesh = o as THREE.Mesh;
      if (!mesh.isMesh) return;
      for (const m of Array.isArray(mesh.material) ? mesh.material : [mesh.material]) {
        this.materials.set(m.name, m);
        const std = m as THREE.MeshStandardMaterial;
        if (std.emissiveMap) lightmaps.add(std.emissiveMap);
        if (std.aoMap) lightmaps.add(std.aoMap);
      }
    });
    setupLightmapFiltering(lightmaps, givre.lightmapMipLevels, getQualitySettings().anisotropy);

    // Static meshes → merged by material, split on the XZ grid (frustum
    // culling + front-to-back), thin closed solids single-sided — see
    // GivreRenderOptim. Shot targets + snow surfaces.
    const merged = new THREE.Group();
    merged.name = "givre_01_merged";
    const { meshes, snow } = mergeStaticBatches(scene, animated);
    for (const mesh of meshes) {
      merged.add(mesh);
      this.hittables.push(mesh);
    }
    // Snow surfaces (footprints): CPU-side queries only — with the uber
    // material the drawn batches mix materials, so the snow is kept as its
    // own (never rendered) merged mesh with the original GIV_Neige material.
    if (snow) this.snowSurfaces.push(snow);
    this.group.add(merged);

    // Animated nodes: never shadow casters. Only collider-backed ones (the
    // boiler) stay shot targets — the rest (steam, smoke, banners,
    // garlands, fans, gauges, beacon) has no server collider: visual only.
    for (const node of nodes.values()) {
      const hittable = colliderSources.has(node.name);
      node.traverse((o) => {
        const mesh = o as THREE.Mesh;
        if (!mesh.isMesh) return;
        mesh.castShadow = false;
        mesh.receiveShadow = true;
        if (!hittable) mesh.raycast = () => {};
      });
      if (hittable) this.hittables.push(node);
    }

    // Repeated puffs → InstancedMesh (sources hidden, still animated).
    const instanced = instanceRepeated(nodes);
    for (const { mesh } of instanced) this.group.add(mesh);

    // PERF: the rest of the animated décor (garlands, banners, pipes,
    // gauges, pumps, boiler…) → skinned batches (~95 draw calls → a few):
    // the constant-only materials share one uber batch, the others get one
    // batch per material. Same nodes, same mixer: see
    // MapBatching.batchAnimatedMeshes.
    const decorBatches = batchAnimatedMeshes(animated, {
      keep: DECOR_KEEP_MATERIALS,
      attributes: [...KEEP_ATTRIBUTES],
      uber: givre.staticBatching.uberMaterial,
    });
    for (const mesh of decorBatches) {
      mesh.name = `givre_${mesh.name}`;
      this.group.add(mesh);
    }

    // What remains of the glb scene: the animated nodes + FX empties.
    // (Their static transforms are frozen with the rest of the map — see the
    // end of the constructor.)
    scene.name = "givre_01_animated";
    this.group.add(scene);
    return { root: scene, clips: gltf.animations, nodes, instanced };
  }

  /**
   * Late-afternoon rig (see GivreConfig):
   *  - HemisphereLight: blue sky over warm snow bounce (π × Blender
   *    strength), switched off indoors by the glb aoMap.
   *  - DirectionalLight sun (WSW, 17°): the only shadow caster. Its
   *    orthographic camera is FITTED to the map box seen from the sun, so
   *    the rectangular shadow map covers the whole playfield (incl. the
   *    north-west Stock) with no wasted texels.
   * No live lamp: the baked emissive lights rooms, garlands and lanterns.
   */
  private buildLighting(): void {
    const hemi = new THREE.HemisphereLight(
      givre.ambientSkyColor,
      givre.ambientGroundColor,
      givre.ambientIntensity,
    );
    this.group.add(hemi);

    const b = givre.shadowBounds;
    const bounds = new THREE.Box3(
      new THREE.Vector3(b.min[0], b.min[1], b.min[2]),
      new THREE.Vector3(b.max[0], b.max[1], b.max[2]),
    );
    const center = bounds.getCenter(new THREE.Vector3()).setY(0);
    const toSun = new THREE.Vector3(
      givre.sunDirection.x,
      givre.sunDirection.y,
      givre.sunDirection.z,
    ).normalize();

    const sun = new THREE.DirectionalLight(givre.sunLightColor, givre.sunLightIntensity);
    sun.target.position.copy(center);
    sun.position.copy(center).addScaledVector(toSun, givre.sunDistance);
    sun.castShadow = true;

    // Fit the shadow camera: the 8 corners of the map box in light space.
    const cam = sun.shadow.camera;
    cam.position.copy(sun.position);
    cam.lookAt(center);
    cam.updateMatrixWorld(true);
    const box = new THREE.Box3();
    const corner = new THREE.Vector3();
    for (let i = 0; i < 8; i++) {
      corner.set(
        i & 1 ? bounds.max.x : bounds.min.x,
        i & 2 ? bounds.max.y : bounds.min.y,
        i & 4 ? bounds.max.z : bounds.min.z,
      );
      box.expandByPoint(corner.applyMatrix4(cam.matrixWorldInverse));
    }
    const margin = 2;
    cam.left = box.min.x - margin;
    cam.right = box.max.x + margin;
    cam.bottom = box.min.y - margin;
    cam.top = box.max.y + margin;
    cam.near = Math.max(0.5, -box.max.z - 10); // the camera looks down −Z
    cam.far = -box.min.z + 10;
    cam.updateProjectionMatrix();

    // Rectangular map: longest side from the quality preset, the other
    // reduced to the map's aspect seen from the sun (4096 × 2048 on HIGH).
    const size = givre.shadowMapSize[getQualitySettings().level];
    const w = cam.right - cam.left;
    const h = cam.top - cam.bottom;
    const side = (ratio: number) =>
      Math.min(size, 2 ** Math.ceil(Math.log2(size * Math.min(1, ratio))));
    sun.shadow.mapSize.set(side(w / h), side(h / w));
    sun.shadow.bias = givre.shadowBias;
    sun.shadow.normalBias = givre.shadowNormalBias;
    this.group.add(sun, sun.target);
  }
}

/**
 * Finds the ANIMATED nodes of the glb: the targets of the clip tracks.
 * Returns them by name, plus the set of every object under them (children
 * included) — none of these may be merged.
 */
function findAnimatedNodes(
  scene: THREE.Object3D,
  clips: THREE.AnimationClip[],
): { nodes: Map<string, THREE.Object3D>; all: Set<THREE.Object3D> } {
  const nodes = new Map<string, THREE.Object3D>();
  const all = new Set<THREE.Object3D>();
  for (const clip of clips) {
    for (const track of clip.tracks) {
      const { nodeName } = THREE.PropertyBinding.parseTrackName(track.name);
      const node = scene.getObjectByName(nodeName);
      if (!node || nodes.has(node.name)) continue;
      nodes.set(node.name, node);
      node.traverse((o) => all.add(o));
    }
  }
  return { nodes, all };
}

/**
 * Replaces every MeshPhysicalMaterial of the glb scene (GLTFLoader creates
 * them for KHR_materials_specular only) by an equivalent
 * MeshStandardMaterial — same name, colours, baked emissive / ao maps,
 * roughness, side, transparency. One replacement per material (shared
 * materials stay shared); the Physical originals are disposed.
 */
function convertToStandardMaterials(scene: THREE.Object3D): void {
  const replaced = new Map<THREE.Material, THREE.Material>();
  const swap = (m: THREE.Material): THREE.Material => {
    let out = replaced.get(m);
    if (!out) {
      out = toStandardMaterial(m);
      replaced.set(m, out);
    }
    return out;
  };
  scene.traverse((o) => {
    const mesh = o as THREE.Mesh;
    if (!mesh.isMesh) return;
    mesh.material = Array.isArray(mesh.material) ? mesh.material.map(swap) : swap(mesh.material);
  });
  for (const [from, to] of replaced) if (from !== to) from.dispose();
}

/**
 * Baked lightmaps: a SHORT mip chain (GivreConfig.lightmapMipLevels) when
 * the image can be downscaled, else the previous no-mipmap setup (a full
 * chain makes the atlas UV islands bleed into each other in the distance).
 * The 36 glTF Texture objects share 2 image sources: the chain is built ONCE
 * per source and given to every texture of that source (three uploads one
 * GL texture per source + sampling parameters).
 */
function setupLightmapFiltering(lightmaps: ReadonlySet<THREE.Texture>, mipLevels: number, anisotropy = 1): void {
  const chains = new Map<string, unknown[] | null>();
  for (const t of lightmaps) {
    let chain = chains.get(t.source.uuid);
    if (chain === undefined) {
      chain = buildLimitedMipmaps(t.image, mipLevels);
      chains.set(t.source.uuid, chain);
    }
    t.generateMipmaps = false;
    if (chain) {
      t.mipmaps = chain as THREE.Texture["mipmaps"];
      t.minFilter = THREE.LinearMipmapLinearFilter;
      // HIGH: anisotropic filtering — floors / walls stay sharp at grazing
      // angles instead of sliding to the blurry small levels.
      t.anisotropy = anisotropy;
    } else {
      t.minFilter = THREE.LinearFilter;
    }
    t.needsUpdate = true;
  }
}

/**
 * Merges every STATIC mesh of the glb scene (one glTF primitive = one
 * three.js Mesh with one material, shared between primitives) and REMOVES
 * them from the scene. Geometry is baked into world space; position +
 * normal + uv survive (v3: `uv` carries the baked light). The merge is done
 * per material (and per side variant), then split on the XZ grid of
 * GivreConfig.staticBatching (GivreRenderOptim.buildStaticBatches). A
 * removed mesh with children (an animated node) is replaced by an empty
 * Object3D holding the SAME local transform, so the parent-relative
 * animation tracks stay valid (attach() would distort them).
 */
function mergeStaticBatches(
  scene: THREE.Object3D,
  animated: ReadonlySet<THREE.Object3D>,
): { meshes: THREE.Mesh[]; snow: THREE.Mesh | null } {
  const entries: StaticEntry[] = [];
  const staticMeshes: THREE.Mesh[] = [];
  scene.traverse((o) => {
    const mesh = o as THREE.Mesh;
    if (!mesh.isMesh || animated.has(mesh)) return;
    staticMeshes.push(mesh);
    const material = mesh.material as THREE.Material;
    // PERF: plain geometries take the direct world-space copy (same values,
    // a fraction of the cost); anything else the generic path.
    let geom = worldSpaceCopy(mesh.geometry, mesh.matrixWorld, KEEP_ATTRIBUTES);
    if (!geom) {
      geom = mesh.geometry.clone().applyMatrix4(mesh.matrixWorld);
      for (const name of Object.keys(geom.attributes)) {
        if (!KEEP_ATTRIBUTES.has(name)) geom.deleteAttribute(name);
      }
    }
    // Mirrored object (negative scale): flip the winding, otherwise it would
    // be seen inside-out once merged (none in v3 — kept for future exports).
    if (mesh.matrixWorld.determinant() < 0 && geom.index) {
      const idx = geom.index.array;
      for (let i = 0; i < idx.length; i += 3) {
        const tmp = idx[i + 1];
        idx[i + 1] = idx[i + 2];
        idx[i + 2] = tmp;
      }
    }
    entries.push({ geometry: geom, material });
  });
  for (const mesh of staticMeshes) {
    const parent = mesh.parent;
    if (!parent) continue;
    if (mesh.children.length > 0) {
      const holder = new THREE.Object3D();
      holder.name = mesh.name;
      holder.position.copy(mesh.position);
      holder.quaternion.copy(mesh.quaternion);
      holder.scale.copy(mesh.scale);
      parent.add(holder);
      for (const child of [...mesh.children]) holder.add(child);
    }
    parent.remove(mesh);
  }

  // Snow surfaces (footprints) BEFORE the uber rewrite: original material,
  // position / normal / uv only — a CPU-side mesh, never rendered.
  let snow: THREE.Mesh | null = null;
  const snowEntries = entries.filter((e) => e.material.name === SNOW_MATERIAL);
  if (snowEntries.length > 0) {
    const geometry = mergeGeometries(snowEntries.map((e) => e.geometry), false);
    if (geometry) {
      snow = new THREE.Mesh(geometry, snowEntries[0].material);
      snow.name = "givre_snow_surfaces";
      snow.matrixAutoUpdate = false;
      snow.raycast = () => {};
    }
  }

  const b = givre.staticBatching;
  // GIV_Feu's emissive is animated through the shared material instance
  // (GivreEffects fire flicker) — never cloned, never merged into the uber.
  const keepMaterials = new Set(["GIV_Feu"]);
  // GIV_Lampe keeps its own batches: its panels never cast (see below).
  if (b.uberMaterial) applyUberMaterial(entries, new Set([...keepMaterials, "GIV_Lampe"]));
  const box = givre.shadowBounds; // playable envelope (X / Z)
  const batches = buildStaticBatches(entries, (g) => mergeGeometries(g, false), {
    grid: {
      minX: box.min[0],
      minZ: box.min[2],
      maxX: box.max[0],
      maxZ: box.max[2],
      cellsX: b.cellsX,
      cellsZ: b.cellsZ,
    },
    chunkMinTriangles: b.chunkMinTriangles,
    singleSidedMaxThickness: b.singleSidedMaxThickness,
    keepMaterials,
  });
  entries.forEach((e) => e.geometry.dispose());

  const out: THREE.Mesh[] = [];
  for (const { geometry, material, cell, singleSided } of batches) {
    geometry.computeBoundingBox();
    geometry.computeBoundingSphere();
    // BVH per batch: O(log n) beam/hitscan raycasts (built once, after the
    // loading screen — see MapBvh).
    queueMapBvh(geometry);
    const mesh = new THREE.Mesh(geometry, material);
    mesh.name = `givre_${material.name}${singleSided ? "_1s" : ""}${cell >= 0 ? `_c${cell}` : ""}`;
    // Emissive lamp panels and transparent materials never cast.
    mesh.castShadow = material.name !== "GIV_Lampe" && !material.transparent;
    mesh.receiveShadow = true;
    mesh.matrixAutoUpdate = false;
    mesh.updateMatrix();
    out.push(mesh);
  }
  return { meshes: out, snow };
}

/**
 * Repeated animated nodes (same geometry + material, no child — v3: the 95
 * smoke / steam puffs over 6 geometries) → one InstancedMesh per group. The
 * source nodes stay animated by the mixer but are hidden; GivreEffects
 * copies their matrices into the instances every frame. 95 → 6 draw calls.
 */
function instanceRepeated(
  nodes: Map<string, THREE.Object3D>,
): { mesh: THREE.InstancedMesh; sources: THREE.Mesh[] }[] {
  const groups = new Map<string, THREE.Mesh[]>();
  for (const node of nodes.values()) {
    const mesh = node as THREE.Mesh;
    if (!mesh.isMesh || mesh.children.length > 0 || Array.isArray(mesh.material)) continue;
    const key = `${mesh.geometry.uuid}/${mesh.material.uuid}`;
    const list = groups.get(key) ?? [];
    list.push(mesh);
    groups.set(key, list);
  }
  const out: { mesh: THREE.InstancedMesh; sources: THREE.Mesh[] }[] = [];
  for (const sources of groups.values()) {
    if (sources.length < INSTANCE_MIN) continue;
    const first = sources[0];
    const im = new THREE.InstancedMesh(first.geometry, first.material, sources.length);
    im.name = `givre_instances_${first.name}`;
    im.instanceMatrix.setUsage(THREE.DynamicDrawUsage);
    im.frustumCulled = false; // moving instances: no reliable bounding sphere
    im.castShadow = false;
    im.receiveShadow = first.receiveShadow;
    im.raycast = () => {}; // steam / smoke never stop a shot
    for (const s of sources) s.visible = false; // still animated, no longer drawn
    out.push({ mesh: im, sources });
  }
  return out;
}

/** Animated materials never batched: GIV_Feu's emissive flickers through the shared instance (GivreEffects). */
const DECOR_KEEP_MATERIALS = new Set(["GIV_Feu"]);

/** One fixed collider of the Yard-format JSON. Returns false on failure. */
function addCollider(
  physics: PhysicsWorld,
  c: GivreColliderEntry,
  collisionGroups?: number,
): boolean {
  if (c.type === "cuboid" && c.position && c.halfExtents) {
    // Axis-aligned by construction (identity rotation in the export).
    physics.addStaticBox(
      c.position[0],
      c.position[1],
      c.position[2],
      c.halfExtents[0] * 2,
      c.halfExtents[1] * 2,
      c.halfExtents[2] * 2,
      undefined,
      collisionGroups !== undefined ? { collisionGroups } : undefined,
    );
    return true;
  }
  if (c.type === "convexHull" && c.vertices) {
    const flat = new Float32Array(c.vertices.flat());
    const collider = physics.addStaticConvexHull(flat);
    if (collider && collisionGroups !== undefined) collider.setCollisionGroups(collisionGroups);
    return collider !== null;
  }
  return false;
}

/** Wireframes: colliders magenta, player clips cyan. Hidden by default. */
function createColliderDebug(
  colliders: GivreColliderEntry[],
  clips: GivreColliderEntry[],
): THREE.Group {
  const group = new THREE.Group();
  group.name = "givre_colliders_debug";
  group.visible = false;
  group.userData.noOutline = true; // never outlined (GivreOutlinePass)
  const solidMat = new THREE.MeshBasicMaterial({ color: 0xff2fd0, wireframe: true, toneMapped: false });
  const clipMat = new THREE.MeshBasicMaterial({ color: 0x2fd0ff, wireframe: true, toneMapped: false });
  const add = (c: GivreColliderEntry, mat: THREE.Material) => {
    let geom: THREE.BufferGeometry;
    if (c.type === "cuboid" && c.position && c.halfExtents) {
      geom = new THREE.BoxGeometry(c.halfExtents[0] * 2, c.halfExtents[1] * 2, c.halfExtents[2] * 2);
      geom.translate(c.position[0], c.position[1], c.position[2]);
    } else if (c.type === "convexHull" && c.vertices) {
      geom = new ConvexGeometry(c.vertices.map((p) => new THREE.Vector3(p[0], p[1], p[2])));
    } else {
      return;
    }
    const mesh = new THREE.Mesh(geom, mat);
    mesh.name = c.id;
    mesh.raycast = () => {}; // debug only: never a hit target
    mesh.frustumCulled = false;
    group.add(mesh);
  };
  colliders.forEach((c) => add(c, solidMat));
  clips.forEach((c) => add(c, clipMat));
  return group;
}
